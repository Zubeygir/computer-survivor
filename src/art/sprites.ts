/** Same pixels with one color swapped. */
function recolor(rows: string[], from: string, to: string): string[] {
  return rows.map((row) => row.split(from).join(to));
}

/** Builds a symmetric sprite from its left half. */
function mirror(rows: string[]): string[] {
  return rows.map((row) => row + [...row].reverse().join(''));
}

/** Second animation frame: the lower half slides one pixel sideways. */
function wiggle(rows: string[]): string[] {
  const middle = Math.floor(rows.length / 2);
  return rows.map((row, i) => (i < middle ? row : row.slice(-1) + row.slice(0, -1)));
}

